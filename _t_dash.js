const puppeteer = require('puppeteer-core');
const CHROME = 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe';
const BASE = 'http://127.0.0.1:8899/aplikasi-parkir';
(async () => {
  const browser = await puppeteer.launch({ executablePath: CHROME, headless: 'new', args: ['--no-sandbox','--disable-dev-shm-usage'] });
  const page = await browser.newPage();
  await page.setViewport({ width: 1440, height: 1000 });
  await page.goto(BASE + '/auth/login.php', { waitUntil: 'networkidle0' });
  await page.type('#username','admin1'); await page.type('#password','123456');
  await Promise.all([page.waitForNavigation({waitUntil:'networkidle0'}), page.click('.login-submit')]);
  const r = await page.evaluate(() => {
    const out = {};
    const g = (sel, prop) => { const el = document.querySelector(sel); if(!el) return 'MISSING:'+sel; const v = getComputedStyle(el)[prop]; return v === undefined ? 'UNDEF' : v; };
    out.topbarBg = g('.topbar','backgroundImage').slice(0,90);
    out.topbarColor = g('.topbar','color');
    out.bodyBg = g('body','backgroundColor');
    out.sidebarBg = g('.sidebar','backgroundColor');
    out.activeNavBg = g('.sidebar a.active','backgroundImage').slice(0,60);
    out.activeNavColor = g('.sidebar a.active','color');
    out.contentPad = g('.content','padding');
    out.statAccent = g('.dashboard-stat','borderTopColor');
    out.panelsCols = g('.dashboard-panels','gridTemplateColumns');
    out.chartBar = g('.revenue-bar','backgroundImage').slice(0,60);
    out.tableHeadBg = g('th','backgroundColor');
    out.tableHeadColor = g('th','color');
    out.radius = g('.dashboard-stat','borderTopLeftRadius');
    out.overflowX = document.documentElement.scrollWidth > window.innerWidth;
    out.docW = document.documentElement.scrollWidth;
    out.statCount = document.querySelectorAll('.dashboard-stat').length;
    out.h1s = [...document.querySelectorAll('h1')].map(h => h.className + '|' + h.textContent.trim().slice(0,30));
    out.statRects = [...document.querySelectorAll('.dashboard-stat')].map(e => { const r=e.getBoundingClientRect(); return [Math.round(r.x),Math.round(r.y),Math.round(r.width),Math.round(r.height)]; });
    out.panelRects = [...document.querySelectorAll('.dashboard-panel')].map(e => { const r=e.getBoundingClientRect(); return [Math.round(r.x),Math.round(r.y),Math.round(r.width),Math.round(r.height)]; });
    const bad = [];
    document.querySelectorAll('.card,.dashboard-stat,.dashboard-panel').forEach(el => { if (el.scrollWidth > el.clientWidth+2) bad.push(el.className+' sw='+el.scrollWidth+' cw='+el.clientWidth); });
    out.overflowIssues = bad;
    return out;
  });
  console.log(JSON.stringify(r, null, 2));
  await browser.close();
})().catch(e => { console.error('ERR ' + e.message); process.exit(1); });